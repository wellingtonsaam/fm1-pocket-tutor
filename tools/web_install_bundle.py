"""T150: the web installer of docs/install/ as one classic script, for pages opened from disk (file://).

docs/install/fm1install.js, fm1ota.js, ports.js and docs/dock.js are ES modules. Chrome does not load modules from
file:// (the page's origin is "null"), and the lessons app (docs/prototipo-aulas.html) is opened that way. This writes
docs/install/fm1install-classico.js: each module in a function of its own (its names stay apart: fm1ota.js and
fm1install.js both have a `fail`), its imports read from the modules before it, its exports on window.FM1Install
(fm1install.js's), window.FM1Ota, window.FM1Ports and window.FM1Dock. The modules stay the source: run this again
after changing them.

    python3 tools/web_install_bundle.py [--check]      (--check: exit 1 if the file is not up to date)
"""
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
OUT = DOCS / "install" / "fm1install-classico.js"
# in dependency order; key = path from docs/
MODULES = [("install/ports.js", "FM1Ports"), ("dock.js", "FM1Dock"), ("install/fm1ota.js", "FM1Ota"),
           ("install/fm1install.js", "FM1Install")]

EXPORT_DECL = re.compile(r"^export\s+((?:async\s+)?function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\}\s*;?\s*$", re.M)
IMPORT = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"([^"]+)"\s*;?\s*$', re.M)


def resolve(base, spec):
    parts = base.split("/")[:-1]
    for seg in spec.split("/"):
        if seg == "..":
            parts.pop()
        elif seg != ".":
            parts.append(seg)
    return "/".join(parts)


def convert(key, src):
    names = [m[2] for m in EXPORT_DECL.finditer(src)]
    for m in EXPORT_LIST.finditer(src):
        names += [n.strip() for n in m[1].split(",") if n.strip()]
    src = EXPORT_LIST.sub("", src)
    src = EXPORT_DECL.sub(lambda m: f"{m[1]} {m[2]}", src)

    def imp(m):
        dep = resolve(key, m[2])
        wanted = [n.strip() for n in m[1].split(",") if n.strip()]
        if any(" as " in n for n in wanted):
            raise SystemExit(f"{key}: 'import {{ a as b }}' is not handled")
        return f'const {{ {", ".join(wanted)} }} = __m["{dep}"];'

    src = IMPORT.sub(imp, src)
    if re.search(r"^\s*(import|export)\b", src, re.M):
        raise SystemExit(f"{key}: an import or export this script does not handle is left")
    src = src.replace("import.meta.url", f'__url("{key}")')
    body = "\n".join("  " + line if line else "" for line in src.rstrip().split("\n"))
    return (f'// ---------------------------------------------------------------- {key} ---\n'
            f'__m["{key}"] = (function () {{\n{body}\n  return {{ {", ".join(names)} }};\n}})();\n')


def build():
    out = ["// GENERATED by tools/web_install_bundle.py from docs/install/ports.js, docs/dock.js, docs/install/fm1ota.js and",
           "// docs/install/fm1install.js (GPL-3.0-only; Felucca's update by Leo Kuroshita, Hügelton Instruments). Do not edit:",
           "// change the modules and run the script again. A classic script, so a page opened from disk (file://) can use it.",
           "(function (g) {",
           '"use strict";',
           "const __m = {};",
           "// a module's own address (its import.meta.url), from the page's: docs/<key>",
           "const __url = (key) => new URL(key, (g.document && g.document.currentScript && g.document.currentScript.src)",
           "  ? new URL(\"../\", g.document.currentScript.src) : (g.document ? g.document.baseURI : \"file:///docs/\")).href;"]
    for key, _ in MODULES:
        out.append(convert(key, (DOCS / key).read_text(encoding="utf-8")))
    for key, name in MODULES:
        out.append(f'g.{name} = __m["{key}"];')
    out.append("})(typeof window !== \"undefined\" ? window : globalThis);\n")
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if same else f"{OUT} is out of date: run tools/web_install_bundle.py")
        sys.exit(0 if same else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.relative_to(DOCS.parent)}: {len(text)} bytes, {len(MODULES)} modules")
