"""T182: monta o app de aulas como PWA em build/fm1-pocket-tutor/, para publicar na Vercel.

O app (docs/prototipo-aulas.html) continua igual e abre do disco como hoje. Esta cópia em build/fm1-pocket-tutor/ ganha:
- index.html = o app, com as fontes servidas junto (pwa/fonts.css, sem Google Fonts), o manifest e o service worker;
- manifest.webmanifest: instala como app e abre em tela cheia, sem a barra de URL do Chrome (display fullscreen,
  com standalone de reserva);
- sw.js: guarda todos os arquivos no aparelho e responde offline; o nome do cache leva o hash dos arquivos, então cada
  publicação nova substitui a anterior na próxima abertura com internet;
- instalar-firmware.html e o pacote do firmware vão junto (o botão Flash FM1 do app abre essa página).
- api/cadastro.js + package.json (T203): o cadastro de nome e email que o botão Flash FM1 pede antes da instalação.

    python3 tools/web_pwa.py            (depois: vercel deploy build/fm1-pocket-tutor --prod --yes)
"""
import hashlib
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = ROOT / "build" / "fm1-pocket-tutor"   # o nome da pasta vira o nome do projeto na Vercel

# o que o app carrega (src/href locais de docs/prototipo-aulas.html e de docs/instalar-firmware.html)
# musicas-locais.js NÃO vai: o próprio arquivo diz "transcrições de músicas protegidas: não publicar";
# o app carrega sem ele (onerror -> lista vazia) e no celular as músicas entram pelo importar MIDI do app.
COPIAR = ["spikes/brilha.js", "spikes/smf.js", "install/fm1install-classico.js",
          "install/pacote-fm1-info.js", "install/pacote-fm1.js", "pwa/icon-192.png", "pwa/icon-512.png",
          "pwa/apple-touch-icon.png"] + [f"pwa/fonts/{p.name}" for p in sorted((DOCS / "pwa" / "fonts").iterdir())]

FONTES = [("Lexend Mega", 700, "lexend-mega-latin-700"), ("Lexend Mega", 900, "lexend-mega-latin-900"),
          ("Public Sans", 400, "public-sans-latin-400"), ("Public Sans", 500, "public-sans-latin-500"),
          ("Public Sans", 700, "public-sans-latin-700"), ("Public Sans", 900, "public-sans-latin-900"),
          ("Space Mono", 400, "space-mono-latin-400"), ("Space Mono", 700, "space-mono-latin-700")]
GOOGLE = re.compile(r'<link[^>]*fonts\.(googleapis|gstatic)\.com[^>]*>\s*')

CABECA = """<script>/* T204: Vercel Web Analytics (conta visitas; sem cookies) */window.va=window.va||function(){(window.vaq=window.vaq||[]).push(arguments)};</script>
<script defer src="/_vercel/insights/script.js"></script>
<link rel="stylesheet" href="pwa/fonts.css">
<link rel="manifest" href="manifest.webmanifest" crossorigin="use-credentials">
<meta name="theme-color" content="#ffe400">
<meta name="mobile-web-app-capable" content="yes">
<link rel="icon" href="pwa/icon-192.png">
<link rel="apple-touch-icon" href="pwa/apple-touch-icon.png">
"""
REGISTRO = """<script>/* T182: PWA — guarda o app no aparelho para abrir offline */
if('serviceWorker' in navigator&&isSecureContext&&location.protocol!=='file:')addEventListener('load',()=>navigator.serviceWorker.register('sw.js').catch(e=>console.warn('sw',e)));
</script>
"""

SW = """// GENERATED by tools/web_pwa.py (T182): guarda o app no aparelho e responde offline.
const CACHE = "fm1-tutor-%(ver)s";
const ARQUIVOS = %(arquivos)s;
self.addEventListener("install", e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(ARQUIVOS)).then(() => self.skipWaiting())));
self.addEventListener("activate", e => e.waitUntil(caches.keys()
  .then(ks => Promise.all(ks.filter(k => k.startsWith("fm1-tutor-") && k !== CACHE).map(k => caches.delete(k))))
  .then(() => self.clients.claim())));
self.addEventListener("fetch", e => {
  const r = e.request;
  if (r.method !== "GET" || new URL(r.url).origin !== location.origin) return;
  e.respondWith(caches.match(r, {ignoreSearch: true}).then(hit => hit || fetch(r).catch(() =>
    r.mode === "navigate" ? caches.match("./") : Response.error())));
});
"""


def pagina(src, troca=()):
    h = (DOCS / src).read_text(encoding="utf-8")
    n = len(GOOGLE.findall(h))
    if n != 3:
        raise SystemExit(f"{src}: esperava 3 links do Google Fonts, achei {n}")
    h = GOOGLE.sub("", h, count=3)
    h = h.replace("</head>", CABECA + "</head>", 1)
    h = h.replace("</body>", REGISTRO + "</body>", 1) if "</body>" in h else h + REGISTRO
    for a, b in troca:
        if a not in h:
            raise SystemExit(f"{src}: não achei {a!r}")
        h = h.replace(a, b)
    return h


def main():
    if OUT.exists():   # limpa tudo menos .vercel (o vínculo com o projeto na Vercel)
        for x in OUT.iterdir():
            if x.name != ".vercel":
                shutil.rmtree(x) if x.is_dir() else x.unlink()
    (OUT / "pwa").mkdir(parents=True)
    # T203: na Vercel, sem língua escolhida (localStorage fm1lang), o app e a página de instalação abrem em inglês
    (OUT / "index.html").write_text(pagina("prototipo-aulas.html", [(
        "const n=(navigator.language||'pt').slice(0,2).toLowerCase();return n==='pt'?'pt':n==='es'?'es':'en'})();",
        "return 'en'})();")]), encoding="utf-8")
    (OUT / "instalar-firmware.html").write_text(
        pagina("instalar-firmware.html", [('location.href = "prototipo-aulas.html"', 'location.href = "./"'),
                                          ('LANG = localStorage.getItem("fm1lang") || "pt";', 'LANG = localStorage.getItem("fm1lang") || "en";'),
                                          ('if (!DICT[LANG]) LANG = "pt";', 'if (!DICT[LANG]) LANG = "en";')]), encoding="utf-8")
    for f in COPIAR:
        (OUT / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(DOCS / f, OUT / f)
    css = "".join(f'@font-face{{font-family:"{fam}";font-style:normal;font-weight:{w};font-display:swap;'
                  f'src:url(fonts/{arq}-normal.woff2) format("woff2")}}\n' for fam, w, arq in FONTES)
    (OUT / "pwa" / "fonts.css").write_text(css, encoding="utf-8")
    man = {"name": "FM1 Pocket Tutor", "short_name": "FM1 Tutor", "id": "./", "start_url": "./", "scope": "./",
           "display": "fullscreen", "display_override": ["fullscreen", "standalone"], "orientation": "any",
           "background_color": "#ffffff", "theme_color": "#ffe400", "lang": "pt-BR",
           "description": "Aulas de teclado com o FM-1: o app mostra e o teclado acende.",
           "icons": [{"src": "pwa/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                     {"src": "pwa/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                     {"src": "pwa/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
    (OUT / "manifest.webmanifest").write_text(json.dumps(man, ensure_ascii=False, indent=1), encoding="utf-8")
    arquivos = sorted(p.relative_to(OUT).as_posix() for p in OUT.rglob("*") if p.is_file() and ".vercel" not in p.parts)
    ver = hashlib.sha256(b"".join((OUT / a).read_bytes() for a in arquivos)).hexdigest()[:10]
    (OUT / "sw.js").write_text(SW % {"ver": ver, "arquivos": json.dumps(["./"] + arquivos, indent=0)}, encoding="utf-8")
    # cabeçalhos da Vercel: o sw.js e o index nunca ficam presos no cache do navegador
    (OUT / "vercel.json").write_text(json.dumps({"headers": [
        {"source": "/sw.js", "headers": [{"key": "Cache-Control", "value": "no-cache"}]},
        {"source": "/(index.html)?", "headers": [{"key": "Cache-Control", "value": "no-cache"}]},
        {"source": "/manifest.webmanifest", "headers": [{"key": "Content-Type", "value": "application/manifest+json"}]}]},
        indent=1), encoding="utf-8")
    # T203: a função /api/cadastro (o modal do FLASH FM1) e o package.json dela; entram depois do sw.js para não irem ao cache offline
    shutil.copytree(ROOT / "tools" / "vercel" / "api", OUT / "api")
    shutil.copy2(ROOT / "tools" / "vercel" / "package.json", OUT / "package.json")
    tam = sum((OUT / a).stat().st_size for a in arquivos)
    print(f"{OUT.relative_to(ROOT)}: {len(arquivos)} arquivos, {tam // 1024} KiB, cache fm1-tutor-{ver}")


if __name__ == "__main__":
    main()
