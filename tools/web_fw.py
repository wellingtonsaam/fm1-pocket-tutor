"""T150: the firmware package the web app installs, as a classic script (docs/install/pacote-fm1.js).

The page docs/instalar-firmware.html is opened from disk (file://), where Chrome refuses fetch(): the package goes in
as base64 inside a script, with what the page shows and checks: identity (FM-1_902), version (the firmware's boot
line, as the FM-1's INFO reports it: "0.1" for a release, the source's commit for any other build), size and SHA-256.
The page checks the bytes again before anything is sent (fm1install.js checkPackage: SHA-256, identity, update loader,
every file's CRC).

    python3 tools/web_fw.py [PACKAGE.fwsc] [--version X]      (default: build/fm1-pocket-tutor.fwsc)
"""
import argparse
import base64
import datetime
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "install" / "pacote-fm1.js"
INFO_OUT = ROOT / "docs" / "install" / "pacote-fm1-info.js"   # T160: só os dados (sem os bytes), para a barra do app
BLOCKS, BLK, KEEP = 20, 0x30, 0x2F


def product_of(raw):
    return "".join(chr((raw[i * BLK + KEEP] - i - 1) & 0xFF) for i in range(BLOCKS) if raw[i * BLK + KEEP] != 0x7D)


def version_of(pkg):
    """the firmware's own version and source, from the build's plain image next to the package (its boot log line:
    "fm1-pocket-tutor 0.2 (eb76e35) boot" for a release, "fm1-pocket-tutor eb76e35+ boot" for any other build)"""
    for cand in (pkg.with_name(pkg.stem + "_xip.bin"), pkg.with_suffix(".bin")):
        if cand.exists():
            m = re.search(rb"fm1-pocket-tutor (\S+)(?: \(([^)\s]+)\))? boot", cand.read_bytes())
            if m:
                v = m[1].decode("latin-1")
                return v, (m[2].decode("latin-1") if m[2] else v)
    return None, None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("package", nargs="?", default=str(ROOT / "build" / "fm1-pocket-tutor.fwsc"))
    ap.add_argument("--version", help="the version the FM-1 will report (default: read from the build)")
    ap.add_argument("--build", help="its source, INFO's build (default: read from the build, else the version)")
    a = ap.parse_args()
    pkg = Path(a.package)
    raw = pkg.read_bytes()
    product = product_of(raw)
    if not re.fullmatch(r"[^_]+_\d+", product):
        raise SystemExit(f"{pkg}: not an FM-1 package (identity {product!r})")
    if b"FELUCCA-LOADER-1" not in raw:
        raise SystemExit(f"{pkg}: no Felucca update loader in it")
    found, src = version_of(pkg)
    version = a.version or found
    if not version:
        raise SystemExit(f"{pkg}: version not found in the build; pass --version")
    meta = {"name": "FM1 Pocket Tutor", "file": pkg.name, "product": product, "version": version, "build": a.build or (src if found == version else version), "size": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "built": datetime.datetime.fromtimestamp(pkg.stat().st_mtime, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%MZ")}
    text = ("// GENERATED by tools/web_fw.py: the firmware package docs/instalar-firmware.html installs (GPL-3.0-only).\n"
            f"// {json.dumps(meta)}\n"
            f"window.FM1_PACOTE = Object.assign({json.dumps(meta)}, {{ b64: \"{base64.b64encode(raw).decode()}\" }});\n")
    OUT.write_text(text, encoding="utf-8")
    INFO_OUT.write_text("// GENERATED by tools/web_fw.py: the version of the firmware docs/instalar-firmware.html installs; the\n"
                        "// lessons app (docs/prototipo-aulas.html) shows FLASH FM1 only when the FM-1 reports another one (T160).\n"
                        f"window.FM1_PACOTE_INFO = {json.dumps(meta)};\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {meta['product']} {meta['version']}, {meta['size']} B, sha256 {meta['sha256'][:12]}…")


if __name__ == "__main__":
    main()
